import assert from 'node:assert/strict';
import {createHoldGesture} from '../src/hold-gesture.js';
let clock=0;
const hold=createHoldGesture({now:()=>clock});
assert.equal(hold.start('pointer:1'),true);
clock=20000;
assert.equal(hold.value(),1);
assert.equal(hold.active,true,'a long hold must never release itself');
assert.equal(hold.release('keyboard'),null,'Space keyup cannot release a mouse hold');
assert.equal(hold.release('pointer:2'),null,'another pointer cannot release a mouse hold');
assert.equal(hold.start('keyboard'),false,'overlapping input must not replace the owner');
assert.equal(hold.active,true);
assert.equal(hold.release('pointer:1'),1);
assert.equal(hold.release('pointer:1'),null,'a duplicate release cannot burst twice');
assert.equal(hold.active,false);
assert.equal(hold.start('keyboard'),true);
clock+=800;
assert.equal(hold.value(),.5);
assert.equal(hold.release('pointer:1'),null);
assert.equal(hold.release('keyboard'),.5);
hold.start('pointer:1');clock+=3000;hold.cancel();
assert.equal(hold.active,false);
assert.equal(hold.release('pointer:1'),null,'cancelled capture or focus must not release later');
console.log('Hold gesture: long hold, input ownership, duplicate release and cancellation passed.');
